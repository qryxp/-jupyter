"""自测：多列指标（3/4列）+ 能力探测/一键计算。

后台/本地用 managed python 跑：python test_multi.py
"""
import pandas as pd
import da

ok = 0
fail = 0


def check(name, cond):
    global ok, fail
    if cond:
        ok += 1
        print(f"  ✅ {name}")
    else:
        fail += 1
        print(f"  ❌ {name}")


print("== 域A 技能外包 · 多列指标 ==")
sk = pd.DataFrame({
    "实收金额": [1000, 2000, 1500],
    "平台抽成": [100, 200, 150],
    "成本": [200, 400, 300],
    "税费": [50, 100, 75],
    "报价金额": [1200, 2400, 1800],
    "交付时长h": [10, 20, 15],
    "渠道来源": ["甲", "乙", "甲"],
})
check("单均净利润", abs(da.技能外包.单均净利润(sk) - (4500 - 450 - 900)) < 1e-6)
check("综合成本率", abs(da.技能外包.综合成本率(sk) - (450 + 900 + 225) / 4500) < 1e-6)
check("时薪净利", abs(da.技能外包.时薪净利(sk) - (4500 - 450 - 900) / 45) < 1e-6)
cn = da.技能外包.渠道净收益率(sk)
check("渠道净收益率(分组)", set(cn.index) == {"甲", "乙"} and len(cn) == 2)

print("== 域B 小微电商 · 多列指标 ==")
ec = pd.DataFrame({
    "销售额": [1000, 2000],
    "成本": [400, 800],
    "平台扣点": [50, 100],
    "推广费": [100, 200],
    "固定成本": [500, 500],
    "单价": [10, 20],
    "单位变动成本": [4, 8],
    "期长天数": [30, 30],
    "销售成本": [300, 600],
    "平均库存": [150, 300],
})
check("销售毛利额", abs(da.小微电商.销售毛利额(ec) - (3000 - 1200 - 150)) < 1e-6)
check("销售净利率", abs(da.小微电商.销售净利率(ec) - (3000 - 1200 - 150 - 300) / 3000) < 1e-6)
check("推广净ROI", abs(da.小微电商.推广净ROI(ec) - (3000 - 1200 - 300) / 300) < 1e-6)
check("盈亏平衡销量", abs(da.小微电商.盈亏平衡销量(ec) - 1000 / (30 - 12)) < 1e-6)
check("库存周转天数", abs(da.小微电商.库存周转天数(ec) - 60 / (900 / 450)) < 1e-6)

print("== 域C 自媒体 · 多列指标 ==")
md = pd.DataFrame({
    "商单收入": [3000, 6000],
    "制作成本": [500, 1000],
    "投放成本": [500, 1000],
    "掉粉数": [20, 40],
    "期初粉丝数": [10000, 10000],
    "新增粉丝数": [2000, 3000],
    "粉丝数": [12000, 13000],
    "月份数": [3, 6],
})
check("内容投产比", abs(da.自媒体.内容投产比(md) - 9000 / 3000) < 1e-6)
check("掉粉率", abs(da.自媒体.掉粉率(md) - 60 / (20000 + 5000)) < 1e-6)
check("千粉月收益", abs(da.自媒体.千粉月收益(md) - 9000 / (25000 / 1000) / 9) < 1e-6)

print("== 域D 零工平台 · 多列指标 ==")
gg = pd.DataFrame({
    "准时交付率": [0.9, 0.8],
    "好评率": [0.95, 0.85],
    "纠纷率": [0.05, 0.1],
    "复购率": [0.3, 0.2],
    "中标数": [10, 20],
    "投标数": [50, 100],
    "复购数": [2, 4],
    "首标时长h": [2, 3],
    "定标时长h": [5, 6],
    "平均交付时长h": [10, 12],
})
check("综合履约分", abs(da.零工平台.综合履约分(gg) - (0.85 * 0.4 + 0.9 * 0.4 + (1 - 0.075) * 0.1 + 0.25 * 0.1)) < 1e-6)
check("复购加权中标率", abs(da.零工平台.复购加权中标率(gg) - (30 + 6 * 0.5) / 150) < 1e-6)
# 任务接标时效：每个任务(首标+定标+交付)的总和，再跨任务取平均
_任1 = 2 + 5 + 10
_任2 = 3 + 6 + 12
check("任务接标时效", abs(da.零工平台.任务接标时效(gg) - (_任1 + _任2) / 2) < 1e-6)

print("== 能力探测 / 一键计算 ==")
# 一份只含部分列的数据：能算销售毛利额/推广净ROI，但差列算不了销售净利率
partial = pd.DataFrame({
    "销售额": [1000, 2000],
    "成本": [400, 800],
    "平台扣点": [50, 100],   # 缺 推广费 → 但推广费是可选列，销售净利率 仍算(按0)
})
可算 = da.可算指标(partial)
可算名 = {m.name for m in 可算}
check("可算指标含 销售毛利额", "销售毛利额" in 可算名)
# 销售净利率 的 推广费/成本/平台扣点 均为可选列 → 缺推广费仍可算
check("可算指标含 销售净利率(推广费为可选列,缺失也算)", "销售净利率" in 可算名)
res = da.一键计算(partial)
check("一键计算返回 销售毛利额 数值", "销售毛利额" in res and res["销售毛利额"] is not None)
check("一键计算返回 销售净利率 数值(缺推广费按0)", "销售净利率" in res and res["销售净利率"] is not None)
# 能力探测应把可选列缺失标注为 ⚠️（而非 🔧 差1列解锁）
print("  (下面 能力探测 输出应显示：销售净利率 ⚠️ 可选列 ['推广费'] 缺失 → 按0算)")
da.能力探测(partial, "小微电商")
da.能力探测(partial)  # 全域

print(f"\n{'='*30}\nMULTI_OK  ✅{ok}  ❌{fail}")
assert fail == 0, f"{fail} 项失败"
print("ALL_MULTI_OK")
