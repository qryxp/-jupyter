"""域A 技能外包 · 可交付项目（直接给客户/给自己出的成品）。

- 收益复盘表  ：周/月接单收益 + 净到手率预警
- 渠道ROI对比 ：哪个平台值得深耕
- 返工热点诊断：哪类需求最容易改
- 报价模拟器  ：输入复杂度/时长 → 推荐报价区间
"""
import pandas as pd

from ..core.utils import 列存在, 安全除法


def 收益复盘表(df, 周期列="日期", 净到手预警线=0.6):
    """按 月 汇总接单收益，并标注净到手率是否低于预警线。"""
    列存在(df, "日期", "报价金额", "实收金额", "平台抽成", "成本", "税费", "返工折损")
    d = df.copy()
    d[周期列] = pd.to_datetime(d[周期列])
    d["周期"] = d[周期列].dt.to_period("M").astype(str)

    def f(x):
        return pd.Series({
            "接单量": len(x),
            "总报价": round(x["报价金额"].sum(), 2),
            "总实收": round(x["实收金额"].sum(), 2),
            "净到手率": 安全除法(
                (x["实收金额"] - x["平台抽成"] - x["成本"] - x["税费"] - x["返工折损"]).sum(),
                x["报价金额"].sum()),
            "总返工单数": int((x["返工次数"] > 0).sum()) if "返工次数" in x else 0,
        })
    g = d.groupby("周期").apply(f).reset_index()
    g["净到手预警"] = g["净到手率"].apply(lambda v: "⚠️偏低" if v < 净到手预警线 else "✅正常")
    return g


def 渠道ROI对比(df):
    """各渠道：接单量、总实收、客单价、净到手率 横向对比。"""
    列存在(df, "渠道来源", "实收金额", "报价金额", "平台抽成", "成本", "税费", "返工折损")

    def f(x):
        return pd.Series({
            "接单量": len(x),
            "总实收": round(x["实收金额"].sum(), 2),
            "客单价": round(安全除法(x["实收金额"].sum(), len(x)), 2),
            "净到手率": 安全除法(
                (x["实收金额"] - x["平台抽成"] - x["成本"] - x["税费"] - x["返工折损"]).sum(),
                x["报价金额"].sum()),
        })
    return df.groupby("渠道来源").apply(f).reset_index()


def 返工热点诊断(df):
    """按 需求类型（没有则按渠道来源）看返工率，定位最容易改的需求。"""
    列存在(df, "返工次数")
    维度 = "需求类型" if "需求类型" in df.columns else ("渠道来源" if "渠道来源" in df.columns else None)
    if 维度 is None:
        return pd.DataFrame({"整体返工率": [float((df["返工次数"] > 0).mean())]})
    return (df.groupby(维度)
              .apply(lambda x: float((x["返工次数"] > 0).mean()))
              .sort_values(ascending=False)
              .rename("返工率")
              .reset_index())


def 报价模拟器(需求复杂度="中", 预计时长h=10, 目标时薪=80, 风险系数=0.2, 单次返工成本=100):
    """输入需求参数，输出推荐报价区间。"""
    系数表 = {"低": 0.8, "中": 1.0, "高": 1.4, "极高": 1.8}
    系数 = 系数表.get(需求复杂度, 1.0)
    基准 = 预计时长h * 目标时薪
    推荐 = 基准 * 系数 * (1 + 风险系数) + 单次返工成本 * 系数
    return {
        "需求复杂度": 需求复杂度,
        "预计时长h": 预计时长h,
        "目标时薪": 目标时薪,
        "推荐报价下限": round(推荐 * 0.9, 1),
        "推荐报价": round(推荐, 1),
        "推荐报价上限": round(推荐 * 1.2, 1),
    }
